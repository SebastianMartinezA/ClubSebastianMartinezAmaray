#!/usr/bin/env python3
"""Generates the launcher icon of the app (no Flutter needed).

The icon is NOT the default Flutter logo: a dark rounded square (#050508, the
app background) with a lime ball (#D4FF00, the club accent) and a dark pentagon,
referencing the sports spaces. The lime is the same accent the design system
reserves for the main action of each screen.

It writes:
  * android/app/src/main/res/mipmap-*/ic_launcher.png   (legacy icons)
  * android/app/src/main/res/drawable/ic_launcher_foreground.xml
    (foreground of the adaptive icon of Android 8+)
  * android/app/src/main/res/drawable/ic_launcher_monochrome.xml
    (monochrome layer for the "themed icons" of Android 13+)

`mipmap-anydpi-v26/ic_launcher.xml` (the adaptive-icon descriptor) is written by
hand and references the two drawables above, so keep its names in sync.

Usage:  python3 tool/generate_icons.py
"""
import math
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ANDROID_RES = os.path.abspath(
    os.path.join(HERE, '..', 'android', 'app', 'src', 'main', 'res')
)

# Palette of the app (see lib/theme/app_theme.dart and docs/design-system.md).
BG = (5, 5, 8)             # #050508, screen background (icon background)
BG_LIGHT = (23, 23, 25)    # #171719, card surface (top of the gradient)
LIME = (212, 255, 0)       # #D4FF00, the club accent (the ball)
LIME_DARK = (150, 182, 0)  # a darker lime for the thin ring around the ball

# density folder -> icon size in pixels
DENSITIES = {
    'mipmap-mdpi': 48,
    'mipmap-hdpi': 72,
    'mipmap-xhdpi': 96,
    'mipmap-xxhdpi': 144,
    'mipmap-xxxhdpi': 192,
}


def pentagon_points(cx, cy, radius, rotation=-math.pi / 2):
    return [
        (
            cx + radius * math.cos(rotation + i * 2 * math.pi / 5),
            cy + radius * math.sin(rotation + i * 2 * math.pi / 5),
        )
        for i in range(5)
    ]


def vertical_gradient(size, top, bottom):
    image = Image.new('RGB', (size, size), top)
    draw = ImageDraw.Draw(image)
    for y in range(size):
        ratio = y / max(size - 1, 1)
        color = tuple(
            int(top[i] + (bottom[i] - top[i]) * ratio) for i in range(3)
        )
        draw.line([(0, y), (size, y)], fill=color)
    return image


def draw_icon(size):
    """Dark rounded square + lime ball with a dark pentagon."""
    image = vertical_gradient(size, BG_LIGHT, BG).convert('RGBA')
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        [(0, 0), (size - 1, size - 1)], radius=int(size * 0.22), fill=255
    )
    image.putalpha(mask)

    draw = ImageDraw.Draw(image)
    center = size / 2
    ball_radius = size * 0.30
    draw.ellipse(
        [
            center - ball_radius,
            center - ball_radius,
            center + ball_radius,
            center + ball_radius,
        ],
        fill=LIME,
    )
    draw.polygon(pentagon_points(center, center, ball_radius * 0.55), fill=BG)

    # Thin darker-lime ring around the ball, like the seams of a football pitch.
    ring = ball_radius * 1.22
    draw.ellipse(
        [center - ring, center - ring, center + ring, center + ring],
        outline=LIME_DARK,
        width=max(1, int(size * 0.02)),
    )
    return image


FOREGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Foreground of the adaptive launcher icon (Android 8+).
     Generated by tool/generate_icons.py: lime ball with a dark pentagon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#D4FF00"
        android:pathData="{circle}" />
    <path
        android:fillColor="#050508"
        android:pathData="{pentagon}" />
</vector>
"""


MONOCHROME_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Monochrome layer of the adaptive launcher icon (Android 13+ "themed icons").
     The system tints this drawable, so it must be a single colour with the shape
     in the alpha channel: a filled disc with the pentagon punched out (evenOdd).
     It cannot reuse `ic_launcher_foreground`, which has two colours: on themed
     icons the pentagon would be painted over and the ball would come out as a
     plain tinted circle. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFF"
        android:fillType="evenOdd"
        android:pathData="{disc} {pentagon}" />
</vector>
"""


def circle_path(cx, cy, radius):
    return (
        f'M{cx - radius},{cy} '
        f'a{radius},{radius} 0 1,0 {radius * 2},0 '
        f'a{radius},{radius} 0 1,0 {-radius * 2},0 Z'
    )


def pentagon_path(cx, cy, radius):
    points = pentagon_points(cx, cy, radius)
    first = points[0]
    path = f'M{first[0]:.2f},{first[1]:.2f} '
    for point in points[1:]:
        path += f'L{point[0]:.2f},{point[1]:.2f} '
    return path + 'Z'


def main():
    for folder, size in DENSITIES.items():
        target = os.path.join(ANDROID_RES, folder)
        os.makedirs(target, exist_ok=True)
        draw_icon(size).save(os.path.join(target, 'ic_launcher.png'))
        print(f'wrote {os.path.join(folder, "ic_launcher.png")} ({size}x{size})')

    drawable = os.path.join(ANDROID_RES, 'drawable')
    os.makedirs(drawable, exist_ok=True)
    xml = FOREGROUND_XML.format(
        circle=circle_path(54, 54, 26),
        pentagon=pentagon_path(54, 54, 14),
    )
    with open(os.path.join(drawable, 'ic_launcher_foreground.xml'), 'w') as handle:
        handle.write(xml)
    print('wrote drawable/ic_launcher_foreground.xml')

    monochrome = MONOCHROME_XML.format(
        disc=circle_path(54, 54, 26),
        pentagon=pentagon_path(54, 54, 14),
    )
    with open(os.path.join(drawable, 'ic_launcher_monochrome.xml'), 'w') as handle:
        handle.write(monochrome)
    print('wrote drawable/ic_launcher_monochrome.xml')

    # Preview at 1024 px, handy to paste in the report or the README.
    preview_dir = os.path.join(HERE, '..', 'docs')
    os.makedirs(preview_dir, exist_ok=True)
    draw_icon(1024).save(os.path.join(preview_dir, 'icon-preview.png'))
    print('wrote docs/icon-preview.png (1024x1024)')


if __name__ == '__main__':
    main()
